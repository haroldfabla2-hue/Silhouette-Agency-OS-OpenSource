"""PROPOSED capsule launcher v3. REVIEWABLE SOURCE ONLY: NOT executed by CI,
NOT wired into any workflow, NOT run during preparation. Execution requires a
separate later authorization after this source and the supervisor are reviewed.

Boundary and trust model:
- Mounts ONLY the audited ALLOWLIST.json manifest (finite /app + runtime),
  never / or the checkout. Resolved sources must stay inside the artifact
  directory; targets are unique and may not overlay /proc, /dev or /work.
- External digest anchor: EXPECTED-DIGESTS.json lives in the REPOSITORY test
  directory (outside the artifact) and pins sha256 of ALLOWLIST.json,
  EMITTED.json, entry, supervisor, fixture and this launcher. The launcher
  validates ITSELF and the artifact against those reviewed digests before
  mounting; internal consistency alone is not identity of reviewed bytes.
  Scope of the anchor: it is a CONSISTENCY anchor only. A passing self-hash
  is an integrity check, NEVER an authorization to run. Any future execution
  must be anchored externally to the reviewed commit, the CI run that
  produced the artifact, and the reviewed artifact bytes (an external review
  record), and the anchor must NOT be regenerated by the same job that runs
  the launcher.
- Modes: every mounted file's mode must equal the manifest's recorded mode;
  runtime executables must carry an executable bit.
- bwrap: --clearenv (environment scrubbed BEFORE Python starts; the trusted
  supervisor reads /app/runtime-env.json itself), --unshare-user with the
  single-uid map (--uid 0), --unshare-pid/net/ipc/uts, --cap-add only
  CAP_NET_ADMIN + CAP_SETPCAP (trusted setup; bounding purge + no_new_privs
  land before any product code), default pid-1 reaper (payload is pid 2),
  --die-with-parent, --new-session, private /proc, minimal /dev, tmpfs /work
  that dies with the namespace.
- External supervision: this launcher imposes its OWN deadline on its OWN
  process tree (start_new_session + killpg of its own pgid only, never a
  global kill). bwrap's pid-1 reaper exits only when the namespace is empty,
  so wait() returning IS the namespace-teardown confirmation; a timeout or
  forced kill is FAIL, never a pass.
Preparation is not isolation proof and not behavior validation."""
import pathlib,json,hashlib,subprocess,sys,os,stat,signal,posixpath
REPO_TEST_DIR=pathlib.Path(__file__).resolve().parent
O=REPO_TEST_DIR.parent.parent/'hydration-gates-capsule-review'
EXTERNAL_WALL_SECONDS=180  # outer bound for a hung supervisor; inner deadline is 120s
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
 expected=json.loads((REPO_TEST_DIR/'EXPECTED-DIGESTS.json').read_text())
 # The launcher validates its own reviewed bytes first.
 assert sha(REPO_TEST_DIR/'launch-capsule.py')==expected['launcherSha256'],'LAUNCHER_SELF_DIGEST'
 assert sha(REPO_TEST_DIR/'inside-supervisor.py')==expected['supervisorSha256'],'SUPERVISOR_SOURCE_DIGEST'
 assert sha(O/'ALLOWLIST.json')==expected['allowlistSha256'],'ALLOWLIST_DIGEST'
 assert sha(O/'EMITTED.json')==expected['emittedSha256'],'EMITTED_DIGEST'
 assert sha(O/'app/hydration-gates-entry.cjs')==expected['entrySha256'],'ENTRY_DIGEST'
 assert sha(O/'app/inside-supervisor.py')==expected['supervisorSha256'],'SUPERVISOR_ARTIFACT_DIGEST'
 assert sha(O/'app/fixture-config.json')==expected['fixtureSha256'],'FIXTURE_DIGEST'
 assert sha(O/'app/native-selection.json')==expected['nativeSelectionSha256'],'NATIVE_SELECTION_DIGEST'
 assert sha(O/'app/native-selection-guard.cjs')==expected['nativeGuardSha256'],'NATIVE_GUARD_DIGEST'
 manifest=json.loads((O/'ALLOWLIST.json').read_text())
 emitted=json.loads((O/'EMITTED.json').read_text())
 assert emitted['productEvaluated'] is False
 o_root=O.resolve();targets=set()
 argv=['bwrap','--clearenv','--unshare-user','--unshare-pid','--unshare-net','--unshare-ipc','--unshare-uts',
       '--uid','0','--gid','0','--cap-add','CAP_NET_ADMIN','--cap-add','CAP_SETPCAP',
       '--die-with-parent','--new-session',
       '--proc','/proc','--dev','/dev','--tmpfs','/work','--chdir','/work']
 # External hash+mode gate: every mounted byte and mode matches the manifest.
 for entry in manifest:
  # Symlink check BEFORE resolve: reject a manifest source that is itself a
  # link (a post-prepare swap would otherwise resolve silently).
  raw=O/entry['source']
  assert not raw.is_symlink(),'MANIFEST_SOURCE_SYMLINK_'+entry['source']
  src=raw.resolve()
  assert src.is_file() and not src.is_symlink(),'MANIFEST_MISSING_'+entry['source']
  assert o_root in src.parents,'MANIFEST_ESCAPE_'+entry['source']
  # Every byte is hashed, including review-only evidence, but ONLY explicit
  # mountable entries become bwrap binds. Review-only cannot have a target.
  assert sha(src)==entry['sha256'],'HASH_GATE_MISMATCH_'+entry['source']
  assert stat.S_IMODE(src.stat().st_mode)==int(entry['mode'],8),'MODE_MISMATCH_'+entry['source']
  if entry['disposition']=='review-only':
   assert entry['target'] is None,'REVIEW_ONLY_HAS_TARGET'
   continue
  assert entry['disposition']=='mountable','UNKNOWN_DISPOSITION'
  # Targets must be canonical absolute POSIX paths under an allowed prefix.
  target=entry['target']
  assert target.startswith('/'),'TARGET_NOT_ABSOLUTE_'+target
  assert posixpath.normpath(target)==target and '..' not in target.split('/'),'TARGET_NOT_CANONICAL_'+target
  assert target.startswith('/app/') or target.startswith('/usr/') or target.startswith('/lib/') or target.startswith('/lib64/'),'TARGET_OUTSIDE_ALLOWED_'+target
  assert target not in targets,'TARGET_DUP_'+target
  assert not (target=='/proc' or target=='/dev' or target=='/work' or target.startswith('/proc/') or target.startswith('/dev/') or target.startswith('/work/')),'TARGET_OVERLAY_'+target
  targets.add(target)
  assert sha(src)==entry['sha256'],'HASH_GATE_MISMATCH_'+entry['source']
  actual_mode=stat.S_IMODE(src.stat().st_mode)
  assert actual_mode==int(entry['mode'],8),'MODE_MISMATCH_'+entry['source']
  if entry['source'].startswith('runtime/usr/bin/') or entry['source'].startswith('runtime/usr/sbin/'):
   assert actual_mode&0o111,'NOT_EXECUTABLE_'+entry['source']
  argv+=['--ro-bind',str(src),target]
 # Node identity cross-check against the compile-time record.
 node=O/'runtime'/emitted['nodeExecPath'].lstrip('/')
 assert sha(node)==emitted['nodeSha256'],'NODE_IDENTITY'
 argv+=['/usr/bin/python3','/app/inside-supervisor.py']
 # External deadline over OUR OWN tree only. bwrap's pid-1 reaper exits only
 # when the sandbox is empty, so a returned wait() confirms namespace teardown.
 proc=subprocess.Popen(argv,start_new_session=True)
 forced=False
 try:
  proc.wait(timeout=EXTERNAL_WALL_SECONDS)
 except subprocess.TimeoutExpired:
  forced=True
  try:os.killpg(proc.pid,signal.SIGKILL)
  except ProcessLookupError:pass
  proc.wait()
 assert not forced,'EXTERNAL_DEADLINE_FORCED_NO_PASS'
 assert proc.returncode==0,'CAPSULE_REJECTED_'+str(proc.returncode)
 print('CAPSULE_ACCEPTED_BY_REVIEWED_SUPERVISOR')
if __name__=='__main__':main()
