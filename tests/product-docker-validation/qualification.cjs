'use strict';
/* SOURCE PROPOSAL. Trusted non-project qualification, PID1 only in this scope.
   Start only inside the separately reviewed container. No child_process import. */
const fs=require('node:fs'),assert=require('node:assert/strict');
const read=p=>fs.readFileSync(p,'utf8');
const status=Object.fromEntries(read('/proc/self/status').split('\n').filter(x=>x.includes(':')).map(x=>[x.slice(0,x.indexOf(':')),x.slice(x.indexOf(':')+1).trim()]));
function verify(){
 assert.equal(process.pid,1);assert.equal(process.version,'v22.18.0');
 const uid=Number(process.env.QUAL_UID),gid=Number(process.env.QUAL_GID);
 assert(Number.isSafeInteger(uid)&&uid>0&&Number.isSafeInteger(gid)&&gid>0);
 assert.deepEqual(status.Uid.split(/\s+/).map(Number),[uid,uid,uid,uid]);
 assert.deepEqual(status.Gid.split(/\s+/).map(Number),[gid,gid,gid,gid]);
 assert.equal(status.Groups,'');
 for(const key of ['CapEff','CapPrm','CapBnd','CapInh','CapAmb'])assert.equal(BigInt('0x'+status[key]),0n);
 assert.equal(status.NoNewPrivs,'1');assert.equal(status.Seccomp,'2');
 assert.equal(read('/proc/self/cgroup').trim(),'0::/');
 assert.deepEqual(read('/proc/net/dev').split('\n').slice(2).filter(x=>x.trim()).map(x=>x.split(':')[0].trim()),['lo']);
 assert(read('/proc/net/route').split('\n').slice(1).every(x=>!x.trim()||x.split(/\s+/)[0]==='lo'));
 assert(read('/proc/net/ipv6_route').split('\n').every(x=>!x.trim()||x.trim().split(/\s+/).at(-1)==='lo'));
 // No metadata-service destination can be routed; no active external probe.
 assert.equal(read('/etc/resolv.conf'),'');
 assert.equal(read('/etc/hostname'),'silhouette-scope\n');
 assert.equal(read('/etc/hosts'),'127.0.0.1 localhost silhouette-scope\n::1 localhost\n');
 for(const p of ['/root','/run','/var/run','/home/runner','/home/sandbox','/memory','/downloads','/opt/silhouette','/etc/shadow','/app/.git','/var/run/docker.sock'])assert(!fs.existsSync(p));
 // Byte-for-byte canonical allowlisted mount plan is checked by host against
 // THIS process mountinfo before GO, including all Docker autogenerated mounts.
 const files=['/proc/self/mountinfo','/proc/self/uid_map','/proc/self/gid_map','/proc/self/limits','/proc/net/route','/proc/net/ipv6_route'];
 const evidence={version:1,phase:'QUALIFIED_INSIDE_NOT_HOST_ENFORCEMENT_PROOF',pid:process.pid,status,files:Object.fromEntries(files.map(p=>[p,read(p)])),links:Object.fromEntries(['net','pid','ipc','uts','mnt','cgroup','user'].map(n=>[n,fs.readlinkSync('/proc/self/ns/'+n)])),devices:fs.readdirSync('/dev').sort(),productPass:false};
 const raw=JSON.stringify(evidence);assert(Buffer.byteLength(raw)<=65536);
 fs.writeFileSync('/evidence/docker-ready-private.json',raw,{flag:'wx',mode:0o600});
}
try{
 verify();
 // Host releases only after actual cgroups/RO/namespace/device/owner/headroom
 // checks. stdin is never passed to product code and cannot run commands.
 const input=Buffer.alloc(3);let count=0;
 while(count<3){const n=fs.readSync(0,input,count,3-count,null);if(!n)throw Error('HOST_RELEASE_MISSING');count+=n;}
 assert.equal(input.toString('ascii'),'GO\n');fs.closeSync(0);
 // The exact unchanged driver starts its own existing125s clock here.
 require('/driver/driver/validate.cjs');
}catch(error){
 try{fs.writeFileSync('/evidence/docker-entry-failed.json',JSON.stringify({version:1,failure:'QUALIFICATION_OR_DRIVER_ENTRY',productPass:false}),{flag:'wx',mode:0o600});}catch{}
 throw error;
}
