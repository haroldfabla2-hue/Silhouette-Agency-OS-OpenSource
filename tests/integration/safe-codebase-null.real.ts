import assert from 'node:assert/strict';
import { CodebaseAwarenessService } from '../../services/codebaseAwareness.ts';
import { localEmbeddingService } from '../../services/localEmbeddingService.ts';
import { vfs } from '../../services/virtualFileSystem.ts';
import { systemBus } from '../../services/systemBus.ts';
import { SystemProtocol } from '../../types.ts';
process.env.SILHOUETTE_INFERENCE_MODE='cloud-only';
let embeddingCalls=0;
const service=new CodebaseAwarenessService(async t=>{ embeddingCalls++; return localEmbeddingService.getEmbedding(t); });
const file:any={id:'PUBLIC_NULL_SOURCE',name:'public.ts',type:'FILE',content:'export const publicSource = "first unembedded content";'};
(service as any).fileHashes.set(file.id,'PUBLIC_PREVIOUS_ACCEPTED_HASH');
await assert.rejects(()=>service.indexFile(file),/embedding unavailable/);
assert.equal((service as any).fileHashes.get(file.id),'PUBLIC_PREVIOUS_ACCEPTED_HASH');
await assert.rejects(()=>service.indexFile(file),/embedding unavailable/,'same content is retried, not cached as success');
await assert.rejects(()=>service.query('PUBLIC QUERY'),/query embedding unavailable/);
(vfs as any).hydrate([{id:'PUBLIC_NULL_PROJECT',parentId:'',name:'Public project',type:'folder'},{id:file.id,parentId:'PUBLIC_NULL_PROJECT',name:file.name,type:'file'}]);
vfs.getNode(file.id)!.content=file.content;
assert.equal(vfs.getProjects().find(p=>p.id==='PUBLIC_NULL_PROJECT')?.rootFolderId,'PUBLIC_NULL_PROJECT');
assert.deepEqual(vfs.getNode('PUBLIC_NULL_PROJECT')!.children,[file.id]);
assert.equal(vfs.getNode(file.id)!.content,file.content);
await assert.rejects(()=>service.indexProject('PUBLIC_NULL_PROJECT'),/embedding unavailable/);
assert.equal((service as any).isIndexing,false,'finally releases project lock');
const unhandled:any[]=[];process.on('unhandledRejection',e=>unhandled.push(e));
const registered=[...(systemBus as any).handlers.get(SystemProtocol.FILESYSTEM_UPDATE)];
const ownCallback=registered[registered.length-1];
assert.equal(typeof ownCallback,'function');
const callsBeforeCallback=embeddingCalls;
await assert.doesNotReject(()=>ownCallback({type:SystemProtocol.FILESYSTEM_UPDATE,payload:{action:'UPDATE',fileId:file.id},initiator:'PUBLIC_FIXTURE',timestamp:Date.now()}));
assert.equal(embeddingCalls,callsBeforeCallback+1,'own callback reached the real disabled embedding');
await new Promise(r=>setTimeout(r,50));
assert.deepEqual(unhandled,[],'async subscriber handles rejected index');
assert.equal((service as any).fileHashes.get(file.id),'PUBLIC_PREVIOUS_ACCEPTED_HASH');
console.log('SAFE_CODEBASE_NULL_PUBLIC_FIXTURE_PASS');
