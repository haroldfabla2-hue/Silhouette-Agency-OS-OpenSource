import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { LanceDbService } from '../../services/lancedbService.ts';
import { UnifiedVectorMemory } from '../../services/unifiedVectorMemory.ts';
import { VectorMemoryService } from '../../services/vectorMemoryService.ts';
import { CodebaseAwarenessService } from '../../services/codebaseAwareness.ts';
import { SemanticMemoryService } from '../../services/semanticMemory.ts';
import { VectorProjectionJournal } from '../../services/vectorProjectionJournal.ts';
import { DreamMemoryQueries } from '../../services/dream/dreamMemoryQueries.ts';
const root = process.env.UNIFIED_MEMORY_TEST_DIR;
assert.ok(root?.includes('/qdrant-eval-'));
const identity = { model: 'PUBLIC_PRECOMPUTED_A', version: '1', dimension: 768 };
const vector = Array(768).fill(0); vector[0] = 1;
const tests: string[] = [];
function check(name: string, value: unknown) { assert.ok(value, name); tests.push(name); }
(async () => {
    const directory = path.join(root, `canonical-${process.pid}`);
    const target = new VectorMemoryService({ enabled: async () => false });
    const canonical = new LanceDbService(directory, target);
    const memory = new UnifiedVectorMemory(canonical);
    const embed = async () => ({ vector, identity });
    const code = new CodebaseAwarenessService({ memory, embed }, false);
    const file: any = { id: 'PUBLIC_CODE', name: 'public.ts', type: 'FILE',
        content: Array.from({ length: 120 }, (_, i) => `export const oldPublic${i} = ${i};`).join('\n') };
    await code.indexFile(file);
    check('real_code_multiple_chunks_retrieved', (await code.query('public', 20)).includes('oldPublic100'));
    await code.indexFile({ ...file, content: 'export const currentPublic = "short version only";' });
    const active = await memory.searchMemory(vector, 50, { type: 'CODE_CHUNK' }, identity);
    check('shrink_hides_old_chunks', active.length === 1 && active[0].payload.content.includes('short version only'));
    check('old_version_preserved_canonically', (await canonical.getAllNodes()).some(n => n.content.includes('oldPublic100')));
    const reopenedCode = new CodebaseAwarenessService({ memory: new UnifiedVectorMemory(new LanceDbService(directory, target)), embed }, false);
    check('active_version_survives_reopen', !(await reopenedCode.query('public', 50)).includes('oldPublic100'));
    let fixtureCalls = 0;
    const interrupted = new CodebaseAwarenessService({ memory, embed: async () => {
        fixtureCalls++;
        return { vector: fixtureCalls === 2 ? [1, 0] : vector, identity };
    } }, false);
    await assert.rejects(() => interrupted.indexFile({ ...file, content: file.content.replaceAll('oldPublic', 'newPublic') }));
    tests.push('actual_invalid_vector_midwrite_rejected');
    check('partial_version_not_activated', (await code.query('public', 50)).includes('short version only') && !(await code.query('public', 50)).includes('newPublic'));
    await code.indexFile({ ...file, content: file.content.replaceAll('oldPublic', 'newPublic') });
    check('failed_version_retry_activates_all_chunks', (await code.query('public', 50)).includes('newPublic100'));
    const semantic = new SemanticMemoryService({ memory, embed });
    await semantic.ingestDocument('Public fixture', 'Public short paragraph retained without Qdrant.');
    check('actual_raptor_leaf_recall', (await semantic.recall('public', 50)).some(n => n.content.includes('short paragraph')));
    await memory.storeMemory('PUBLIC_INTUITION', vector, { content: 'Public hypothetical intuition', tags: ['INTUITION', 'HYPOTHESIS'] }, identity);
    check('actual_dream_duplicate_query', await new DreamMemoryQueries(memory, embed).isRedundant('public'));
    check('same_dimension_other_model_excluded', (await memory.searchMemory(vector, 50, undefined, { ...identity, model: 'PUBLIC_OTHER_MODEL' })).length === 0);
    await assert.rejects(() => memory.storeMemory('UNVERIFIED', vector, { content: 'Public' })); tests.push('unverified_identity_rejected');
    const other = Array(768).fill(0); other[0] = 0.6; other[1] = 0.8;
    await memory.storeMemory('PUBLIC_DISTANT', other, { content: 'Public distant', ownerId: 'PUBLIC_A' }, identity);
    check('score_band_before_topk', (await memory.searchDistantMemories(vector, 0.5, 0.7, 2, identity))[0]?.id === 'PUBLIC_DISTANT');
    check('owner_scope_excludes_other', (await memory.searchMemory(vector, 50, { ownerId: 'PUBLIC_B' }, identity)).length === 0);
    const current = (await canonical.getNodeById('PUBLIC_DISTANT'))!;
    await canonical.store({ ...current, content: 'Public changed without embedding' });
    check('stale_vector_excluded_after_content_change', !(await memory.searchMemory(vector, 50, undefined, identity)).some(p => p.id === 'PUBLIC_DISTANT'));
    const brand = { content: 'Public brand', manifesto: { toneOfVoice: ['calm'] }, designSystem: { typography: { usageRules: 'public' }, logoRules: { clearance: 'public' } } };
    await memory.storeMemory('PUBLIC_BRAND', vector, brand, identity);
    check('brand_rules_without_qdrant', (await memory.queryBrandRules('PUBLIC_BRAND', 'public')).includes('calm'));
    check('brand_feedback_no_inference', await memory.updateManifesto('PUBLIC_BRAND', 'Public feedback'));
    check('brand_feedback_persists', (await memory.getBrandTwin('PUBLIC_BRAND'))?.evolutionLog[0]?.feedback === 'Public feedback');
    const journal = new VectorProjectionJournal(path.join(directory, 'vector-projection-intents.sqlite'));
    check('payload_feedback_retains_replay_intent', journal.pending(500).some(i => i.id === 'PUBLIC_BRAND' && i.node.evolutionLog?.[0]?.feedback === 'Public feedback'));
    journal.close();
    const localIdentity = { model: 'PUBLIC_PRECOMPUTED_LOCAL', version: '1', dimension: 384 };
    const local = Array(384).fill(0); local[0] = 1;
    await memory.storeMemory('PUBLIC_LOCAL_384', local, { content: 'Public local identity preserved' }, localIdentity);
    check('local_384_canonical_retrieval', (await memory.searchMemory(local, 2, undefined, localIdentity))[0]?.id === 'PUBLIC_LOCAL_384');
    const result = { scope: 'Real canonical consumer acceptance with configured-disabled Qdrant, public precomputed vectors, no models. NOT Qdrant replay/full suite/learning acceptance.', tests };
    fs.writeFileSync(process.env.QDRANT_CONSUMER_TEST_RESULT!, JSON.stringify(result, null, 2));
    console.log(JSON.stringify(result)); process.exit(0);
})().catch(error => { console.error(error); process.exit(1); });
