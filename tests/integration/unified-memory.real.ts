import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { LanceDbService } from '../../services/lancedbService.ts';
import { UnifiedVectorMemory } from '../../services/unifiedVectorMemory.ts';
import { VectorMemoryService } from '../../services/vectorMemoryService.ts';
import { VectorProjectionJournal } from '../../services/vectorProjectionJournal.ts';
import { CodebaseAwarenessService } from '../../services/codebaseAwareness.ts';
import { SemanticMemoryService } from '../../services/semanticMemory.ts';
import { DreamMemoryQueries } from '../../services/dream/dreamMemoryQueries.ts';
const base = process.env.QDRANT_CONSUMER_TEST_URL;
assert.match(base || '', /^http:\/\/127\.0\.0\.1:\d+$/);
const root = process.env.UNIFIED_MEMORY_TEST_DIR;
assert.ok(root && root.includes('/qdrant-eval-'));
const dir = path.join(root, `unified-${process.pid}`);
const collection = `test_unified_${process.pid}`;
const vector = Array(768).fill(0); vector[0] = 1;
const identity = { model: 'PUBLIC_PRECOMPUTED_A', version: '1', dimension: 768 };
const otherIdentity = { ...identity, model: 'PUBLIC_PRECOMPUTED_B' };
const tests: string[] = [];
function check(name: string, value: unknown) { assert.ok(value, name); tests.push(name); }
async function api(suffix: string, method = 'GET', body?: any) {
    const r = await fetch(base + suffix, { method, headers: { 'Content-Type': 'application/json', 'Connection': 'close' }, body: body && JSON.stringify(body) });
    return { status: r.status, body: await r.json() };
}
(async () => {
    const target = new VectorMemoryService({ url: base, collectionName: collection, enabled: async () => true });
    const canonical = new LanceDbService(dir, target);
    const unified = new UnifiedVectorMemory(canonical);
    const embed = async () => ({ vector, identity });
    const code = new CodebaseAwarenessService({ memory: unified, embed }, false);
    const file: any = { id: 'public-code', name: 'public.ts', type: 'FILE', content: 'export const greeting = "public canonical";' };
    await code.indexFile(file);
    check('code_retrievable_with_qdrant_down', (await code.query('public')).includes('public canonical'));
    const longFile = { ...file, id: 'public-multichunk', content: Array.from({length: 120}, (_, i) => `export const oldPublic${i} = ${i};`).join('\n') };
    await code.indexFile(longFile);
    await code.indexFile({ ...longFile, content: 'export const currentPublic = "short version only";' });
    const shrinkResults = await unified.searchMemory(vector, 50, { type: 'CODE_CHUNK' }, identity);
    check('code_shrink_hides_old_chunks_without_deleting', !shrinkResults.some(n => n.payload.content.includes('oldPublic')) && shrinkResults.some(n => n.payload.content.includes('short version only')));
    const semantic = new SemanticMemoryService({ memory: unified, embed });
    await semantic.ingestDocument('Public fixture', 'Public short paragraph retained without Qdrant.');
    check('raptor_leaf_canonical_without_qdrant', (await semantic.recall('public')).some(n => n.content.includes('short paragraph')));
    await unified.storeMemory('public-intuition', vector, { content: 'Public hypothetical intuition', tags: ['INTUITION','HYPOTHESIS'] }, identity);
    const dream = new DreamMemoryQueries(unified, embed);
    check('real_dream_query_works_without_qdrant', await dream.isRedundant('public duplicate'));
    check('unverified_identity_rejected', await unified.searchMemory(vector).then(() => false, () => true));
    check('same_dimension_other_model_isolated', (await unified.searchMemory(vector, 50, undefined, otherIdentity)).length === 0);
    const distant = Array(768).fill(0); distant[0] = 0.6; distant[1] = 0.8;
    await unified.storeMemory('public-distant', distant, { content: 'Public distant concept', ownerId: 'PUBLIC_A' }, identity);
    check('actual_distant_band_works', (await unified.searchDistantMemories(vector, 0.5, 0.7, 4, identity)).some(n => n.id === 'public-distant' && Math.abs(n.score - 0.6) < 0.001));
    check('owner_filter_excludes_other_owner', !(await unified.searchMemory(vector, 50, { ownerId: 'PUBLIC_B' }, identity)).some(n => n.id === 'public-distant'));
    const journal = new VectorProjectionJournal(path.join(dir, 'vector-projection-intents.sqlite'));
    check('projection_intent_survives_outage', journal.pending(50).length >= 4);
    journal.close();
    await api('/collections/' + collection, 'PUT', { vectors: { size: 768, distance: 'Cosine' }, wal_config: { wal_capacity_mb: 1 } });
    const reopened = new LanceDbService(dir, target);
    const replay = await reopened.replayVectorProjections(50);
    check('real_projection_replays_after_reopen', replay.completed >= 4);
    const mirrored = await target.searchMemory(vector, 50, { _embeddingModel: identity.model });
    check('replay_keeps_identified_payload', mirrored.some(n => n.id === 'public-intuition' && n.payload._embeddingVersion === '1'));
    check('replay_is_idempotent', (await reopened.replayVectorProjections(50)).completed === 0);
    const all = await canonical.getAllNodes();
    const current = all.find(n => n.id === 'public-distant')!;
    await canonical.store({ ...current, tags: ['PUBLIC_UPDATED_METADATA'] });
    check('query_hydrates_latest_canonical', (await unified.searchMemory(vector, 50, undefined, identity)).some(n => n.id === current.id && n.payload.tags.includes('PUBLIC_UPDATED_METADATA')));
    const brand: any = { id: 'PUBLIC_BRAND', content: 'Public brand twin', manifesto: { toneOfVoice: ['calm'] }, designSystem: { typography: { usageRules: 'public' }, logoRules: { clearance: 'public' } } };
    await unified.storeMemory(brand.id, vector, brand, identity);
    await api('/collections/' + collection, 'DELETE');
    check('brand_rules_canonical_after_projection_down', (await unified.queryBrandRules(brand.id, 'public')).includes('calm'));
    check('brand_feedback_canonical_no_inference', await unified.updateManifesto(brand.id, 'Public feedback'));
    check('brand_feedback_retained', (await unified.getBrandTwin(brand.id))?.evolutionLog?.[0]?.feedback === 'Public feedback');
    fs.writeFileSync(process.env.QDRANT_CONSUMER_TEST_RESULT!, JSON.stringify({ scope: 'Real app consumers with real LanceDB, real Qdrant outage/reopen/replay, identified public precomputed vectors, no models', tests }, null, 2));
    console.log(JSON.stringify({ tests }));
    process.exit(0);
})().catch(error => { console.error(error); process.exit(1); });
