import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createHash, randomUUID } from 'node:crypto';
import * as lance from '@lancedb/lancedb';
import { LanceDbService } from '../../services/lancedbService.ts';
const root = process.env.CANONICAL_IDENTITY_TEST_DIR || path.join(os.tmpdir(), 'canonical-identity-' + randomUUID());
assert.ok(path.isAbsolute(root));
assert.ok(!fs.existsSync(root));
fs.mkdirSync(root);
process.env.VECTOR_ENGINE = 'scan';
process.env.LANCEDB_SCAN_PAGE_ROWS = '2';
process.env.LANCEDB_OPTIMIZE_INTERVAL_MINUTES = '0';
const a = { model: 'PUBLIC_IDENTITY_A', version: '1', dimension: 768 }, b = { model: 'PUBLIC_IDENTITY_B', version: '1', dimension: 768 };
const vector = Array(768).fill(0);
vector[0] = 1;
const node = (id: string, content: string, embeddingIdentity = a, ownerId = 'PUBLIC_OWNER') => ({ id, content, embeddingIdentity, ownerId, tags: ['PUBLIC'], tier: 'DEEP', timestamp: 1, importance: 0.1, accessCount: 0, lastAccess: 1 });
const service = new LanceDbService(root + '/lance');
const stale = node('PUBLIC_STALE', 'Public formerly A');
await service.store(stale as any, vector);
await service.store({ ...stale, content: 'Public now B', embeddingIdentity: b } as any);
const content = node('PUBLIC_CONTENT', 'Public old content');
await service.store(content as any, vector);
await service.store({ ...content, content: 'Public updated content without vector' } as any);
for (let i = 0; i < 5; i++) {
    const n = node('PUBLIC_REJECT_' + i, 'Public projection old ' + i);
    await service.store(n as any, vector);
    await service.store({ ...n, embeddingIdentity: b } as any);
}
const good = node('PUBLIC_VALID_LATER', 'Public valid later page');
const lower = [...vector];
lower[0] = 0.8;
lower[1] = 0.6;
await service.store(good as any, lower);
const owner = node('PUBLIC_OWNER_CHANGED', 'Public owner changed');
await service.store(owner as any, vector);
await service.store({ ...owner, ownerId: 'OTHER_OWNER' } as any);
const tier = node('PUBLIC_TIER_CHANGED', 'Public tier changed');
await service.store(tier as any, vector);
await service.store({ ...tier, tier: 'SHALLOW' } as any);
const good2 = node('PUBLIC_VALID_SECOND', 'Public second valid later page');
const lower2 = [...vector];
lower2[0] = 0.6;
lower2[1] = 0.8;
await service.store(good2 as any, lower2);
for (const id of ['PUBLIC_MISSING', 'PUBLIC_MALFORMED_CANONICAL', 'PUBLIC_MALFORMED_PROJECTION'])
    await service.store(node(id, 'Public malformed control') as any, vector);
const foreign = node('PUBLIC_FOREIGN', 'Public foreign valid', a, 'OTHER_OWNER');
await service.store(foreign as any, vector);
const db = await lance.connect(root + '/lance');
const snapshot = async () => { const r: any = {}; for (const name of await db.tableNames()) {
    const t = await db.openTable(name);
    r[name] = { version: await t.version(), schema: String(await t.schema()), rowsSha: createHash('sha256').update(JSON.stringify(await t.query().toArray())).digest('hex') };
} return r; };
const canonical = await db.openTable('memory_records_v2');
await canonical.delete("id = 'PUBLIC_MISSING'");
await canonical.update({ where: "id = 'PUBLIC_MALFORMED_CANONICAL'", values: { json_data: '{broken' } });
const projection = await db.openTable('memory_vectors_' + createHash('sha256').update(JSON.stringify(a)).digest('hex').slice(0, 24));
await projection.update({ where: "id = 'PUBLIC_MALFORMED_PROJECTION'", values: { json_data: '{broken' } });
const before = await snapshot();
const results = await service.search(vector, 2, "`ownerId` = 'PUBLIC_OWNER' AND json_data LIKE '%DEEP%'", a);
assert.deepEqual(results.map(n => n.id), [good.id, good2.id], 'invalid higher-ranked rows must not hide valid later-page candidate');
const all = await service.search(vector, 20, undefined, a);
assert.ok(!all.some(n => n.id === stale.id || n.id === content.id || n.id.startsWith('PUBLIC_REJECT_')));
assert.ok(all.some(n => n.id === foreign.id));
assert.ok(!all.some(n => n.id === owner.id || n.id === 'PUBLIC_MISSING' || n.id.startsWith('PUBLIC_MALFORMED_')));
assert.ok(!(await service.search(vector, 20, "json_data LIKE '%DEEP%'", a)).some(n => n.id === tier.id), 'SQL scope must be evaluated on canonical, not only projection');
assert.deepEqual(await service.search(vector, 1, "id = 'PUBLIC_VALID_LATER'", a), [good]);
const invalid = await service.search(vector.slice(0, 2), 5, undefined, a);
assert.deepEqual(invalid, []);
assert.deepEqual(await snapshot(), before, 'query must not rewrite canonical/vector schema, rows or versions');
assert.deepEqual(await service.getNodeById(stale.id), { ...stale, content: 'Public now B', embeddingIdentity: b });
fs.writeFileSync(root + '/result.json', JSON.stringify({ scope: 'Actual isolated Lance canonical/projection read validation; no generation/ABA/cloud/model/E2E claims', invalidHighRankSkippedBeforeLimit: true, laterPageValidReturned: true, contentMismatchExcluded: true, identityMismatchExcluded: true, ownerFilterPreserved: true, canonicalSqlFilterPreserved: true, ownerChangeExcluded: true, queryDoesNotWrite: true, missingAndMalformedExcluded: true, returnedK: 2, results: results.map(n => n.id) }, null, 2));
